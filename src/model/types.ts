// ============ 静态表（data/ 的静态表都用这里的类型） ============

export type CategoryId = 'food' | 'water' | 'medicine' | 'fuel' | 'warmth' | 'tool' | 'luxury';

/**
 * 内容的**分层**（§10B.5 第 3 件）：
 *
 *   1 = 开局就撞得到（第一次玩就见到）
 *   2 = 需要一点针对性（专门去买 / 专门去配）
 *   3 = 稀有（低概率、要运气或者要攒）
 *   4 = 极稀有（要解锁才拿得到）
 *
 * ## 为什么必须有这个字段
 *
 * §10B 要把内容从 17 件物资 / 6 条夜间事件扩到**数百种**。
 * 一次性涌进来会把新玩家淹掉 —— 第一局就想让他看懂 200 件物资，
 * 结果是他一件也记不住。`tier` 是"渐进放出来"的**唯一手段**：
 * 有了它，将来任何一处筛选（开局货架 / 事件池 / 解锁阶梯）都只需要读一个数。
 *
 * ## ★ 现在的边界（写清楚，免得被误认为已经生效）
 *
 * **M3 第 1 步只做"把分层写成数据 + 让校验器盯着它"，还没有任何筛选读它。**
 * 也就是说：给某条内容标 `tier: 3` **不会**让它不出现在第一期。
 * 真正开始按 tier 放内容，是内容量上去之后（§10B 第 8 步）才做的事。
 *
 * 现在就把字段落下来的理由只有一个，但很硬：**内容量上去之后再补分层，
 * 就得回头给几百条内容逐条想一遍"它算第几层"** —— 那件事的成本随内容量线性增长，
 * 而它现在只有几十条。
 *
 * ## 为什么是"可选字段 + 构建期必填"
 *
 * 类型上可选，是因为内容表将来可以来自 mod（§10B.5「mod 友好的三条」）——
 * 一个第三方内容包不该因为少了一个字段就编译不过。
 * 但**本仓库自己的内容必须写**：`scripts/check-content.mjs` 的"可达性"那一条
 * 会把没写 tier 的条目标成不合格（M2 的 D-16 就是"写了但永远出不来"的那类问题）。
 * 一道守编译期、一道守构建期，各管各的读者。
 */
export type ContentTier = 1 | 2 | 3 | 4;

/** 四层的展示名（图鉴 / 解锁提示共用一份中文，免得两处各写一遍） */
export const TIER_LABELS: Record<ContentTier, string> = {
  1: '常见',
  2: '少见',
  3: '稀有',
  4: '罕见'
};

export interface ItemDef {
  id: string; // 'canned_beans'
  name: string; // '黄豆罐头'
  category: CategoryId;
  icon: string; // emoji 或 svg key
  unitWeight: number; // kg/件
  /*
   * ★ `slotSize` 在这里**被删掉了**（2026-10，清偿 D-07）。
   *
   * 它原来是"占用槽位数（1=小件 / 2=大瓶 / 4=整袋米）"，而**没有任何代码读它** ——
   * 槽位矩阵实际是"一格一栈"，所以大米（写过 4）和电池占同样一格。
   * 而 121 条数据全都老老实实写着 1 / 2 / 4：那是**纯装饰**，
   * 比"没写"更坏 —— 下一个人会以为空间是有区别的。
   *
   * D-07 自己给的两条路是"要么让它真的吃格子，要么删掉"。选了删，
   * 而"让它吃格子"（一袋米占四格）**登记成了 M4 的候选** ——
   * 那件事要同时动放置 / 合并 / 拖动 / 容量 / 存档五处，属于
   * §10.1A "整理本身要有更多决定" 那一条的正题，不是 M3 的补丁。
   */
  stackLimit: number; // 单槽堆叠上限
  perishable: boolean;
  shelfLifeDays?: number; // 保质期（perishable=true 必填）
  nutrition: Partial<{ food: number; water: number; health: number; comfort: number }>;
  basePrice: number;
  tags: string[]; // 供玩家分区规则引用：'canned','drink','medkit'...
  /** 内容分层，见 `ContentTier`。本仓库的内容必须写，由 `check-content.mjs` 盯 */
  tier: ContentTier;
  /**
   * 生成时写下的一句「它逼玩家做什么决定」。
   *
   * ★ 它**不参与任何玩法**，是**内容评审的留痕**：§10B.6 要求每一批内容
   * "同一类取舍不许超过 5 条"，而验收这件事需要每条自带那句话才能归类数一遍。
   * 生成物里它本来就是必填（见 `docs/囤货末世-游戏策划案.md` §10B.7 的提示词），
   * 所以入库时把它**留着**而不是删掉 —— 删了将来就再也无法回答
   * "这 57 件物资是不是三十件都在逼同一个决定"。
   */
  decision?: string;
  /** 生成时写下的一句备注（同样是评审留痕，不参与玩法）。入库后保留，理由同 `decision` */
  note?: string;
}

export interface DisasterProfile {
  /**
   * 灾难 id。
   *
   * ## ★ 为什么从字面量联合类型改成了 `string`（与 `ShopId` 同一条理由）
   *
   * 原来是 `'cold_snap' | 'heat_wave' | 'flood' | 'epidemic'` ——
   * 它顺便限制了"最多 4 场灾难"，而 §10B 要把灾难扩到 **12~16 场**。
   * 每加一场都要改这个类型 = 违背"加内容 = 加一行数据"。
   *
   * 约束改由两道守：`data/disaster.ts` 的 `hasDisasterDef()`（运行期，
   * 存档自愈用它）+ `scripts/check-content.mjs`（构建期）。
   */
  id: string;
  name: string;
  calendar: DayForecast[]; // 先知日历：逐日强度曲线
  dailyDrain: Partial<Record<CategoryId, number>>; // 每日额外消耗权重
  /**
   * 逐日**外界温度**（°C）。**必填**，理由是 D-15：
   *
   * 它原来是一张写死在 `data/disaster.ts` 里的 `COLD_SNAP_TEMPS` 常量表，
   * 只覆盖寒潮 —— 于是"再加一场灾难"就必须再写一张表，而"加内容 = 加一行数据"
   * 这条规矩当场失效（D-15 记的就是这件事）。
   *
   * 挪进 `DisasterProfile` 之后，**每一场灾难自带自己的温度曲线**，
   * 而这正是 §6.6 反差层要的东西：寒潮的 -30 与热浪的 +41 是同一套渲染的两个极端。
   *
   * 用**必填**而不是可选，与 `spoilRate` 同一个理由：
   * 加第 2 场灾难时忘记想"这场外界是什么温度"会直接编译不过。
   */
  temperatures: Record<number, number>;
  priorityCategories: CategoryId[]; // 寒潮→['fuel','warmth']
  windowScene: string; // 窗外渲染主题 key
  /**
   * 灾难期腐坏倍率 —— 相对策划案 §7 的**新增字段**，理由见 src/meta/deferred.ts 的 D-03。
   *
   *   1   = 真实保质期，不动
   *   > 1 = 加速腐坏（过一天算更多天，寿命变短）—— 热浪 / 洪水 / 疫情
   *   < 1 = 延长（过一天算更少天，寿命变长）—— 寒潮：室外本身就是冷库
   *
   * 只在 `day >= 0`（灾难已登陆）时生效；囤货期永远是真实速度。
   * 用**必填**而不是可选：将来加进第 2、第 3 个灾难时，忘记想"这场怎么处理腐坏"
   * 会直接编译不过 —— 这条设计决定（"腐坏是灾难的属性"）需要被类型系统记住。
   */
  /**
   * 每年/每天/每秒的腐坏倍率。
   *
   * 只在 `day >= 0`（灾难已登陆）时生效；囤货期永远是真实速度。
   */
  spoilRate: number;

  /**
   * ★ 这一场是不是**断了电** —— 断电时冰箱的 `spoilFactor` 按 1 算（就是个箱子）。
   *
   * ## 为什么它是"腐坏速度"这一维里的一个取值，而不是第 18 维
   *
   * ★ 这里原来还有一句"第 17 维那个字段至今引擎没实现，写了会静默失效" ——
   * 2026-10 那个字段**已经删掉了**（第 17 维只剩一个维度编号，读不到任何东西，
   * 见 `data/disasterDimensions.ts` 与 D-35）。它当时的道理仍然成立：
   * 这里要的是一件**真的会改数值**的事，**而它读的乘数本来就是第 2 维那一个**
   * （`spoilRate × spoilFactor`）：
   * 只是"家具那一半"在这一场里对冰箱失效。所以它算第 2 维的取值，
   * `data/disasterDimensions.ts` 的清单**不加行**（加了会让"用到几维"虚高，
   * 而那正是决策 C 花力气清掉的那笔账）。
   *
   * ## 它解决的账（D-31）
   *
   * 冰箱原先是**严格支配**另外两种家具的（同价、同格、`spoilFactor` 最低），
   * 于是"加家具三选一"里有两个决定永远不会被选。断电给了它一个**会真的发生的**代价：
   * 「电网崩了」「酷暑断电」「大停电」那一类场次里，花一样的钱买的冰箱
   * **在最需要它的时候停摆** —— 而柜子不怕断电，于是那几场里柜子才是对的。
   *
   * ## 边界（写给下一个改这里的人）
   *
   * · 只对 `kind === 'fridge'` 生效。柜子 / 货架 / 地面**不受影响** ——
   *   断电不是"全屋没有保护"，是"只有需要电的那一种停了"；
   * · 它**不改 `spoilRate`**：外面该多热还是多热，热的还是那些**在冰箱里**的东西。
   *   把两者混起来会得到"断电等于腐坏加快"，而那会让"放进柜子"这条出路消失；
   * · 必须有 `notes` 里的证据。`data/disaster.test.ts` 会守着这条：
   *   `fridgeDead: true` 的场次，`notes` 里必须出现「断电 / 停电 / 冰箱 / 冷藏 / 冷链」之一 ——
   *   否则它就是一个**玩家读不出理由**的机制（也多半是复制粘贴贴错了行）。
   */
  fridgeDead?: boolean;

  // ———————— §10B.3.1 的 L2 影响维度（全部可选，不写 = 1 / 0） ————————
  /*
   * ## 为什么这些字段必须是"可选 + 默认 1"而不是必填
   *
   * 寒潮（唯一的存量灾难）不需要它们 —— 强制必填会逼着给寒潮编一堆 1，
   * 而那些 1 会掩盖"寒潮真的没有这条影响"这个事实。
   * 所以：**不写 = 这一维在这场上不起作用**，而不是"值等于 1"。
   *
   * ## 为什么它们值得存在（用户的原话）
   *
   * "灾难是要跟其他所有一切做衔接的……多角度全方位影响的。"
   * 只靠消耗/腐坏/刚需/温度那 4 维，一百场灾难会写成"十二种 × 八种数值"。
   * 这 8 个字段把灾难从"数字变了"推进到"**生活方式变了**"：
   * 屋子坏得更快、睡不安稳、搬得更少、门开得少、什么都贵、碰上的人不一样。
   *
   * 每一项都标了它在代码里的**唯一读点** —— 加维度时照着那个点接就行，
   * 不要在多处各算一份（那正是"两份状态各自漂移"的老毛病）。
   */

  /** 屋子每天额外掉多少庇护所（负数 = 更坏）。读点：`systems/survival.ts` 的日结算 */
  shelterDecayPerDay?: number;
  /** 睡觉回复体力的**乘数**（0.6 = 只回六成）。读点：`data/survival.ts` 的 `sleepRecoverAt` */
  restEfficiency?: number;
  /** 单趟搬运上限的**乘数**（0.7 = 高温/风雪里一趟少提三成）。读点：`systems/shop.ts` 的 `buildCartView` */
  carryFactor?: number;
  /** 每天行动点增减（-1 = 天黑得早，一天少做一件事）。读点：`systems/phases.ts` 的 `endDay` */
  actionPointDelta?: number;
  /** 商店库存乘数（0.5 = 大半货架空着）。读点：`systems/shop.ts` 的 `rollShopStocks` */
  shopSupplyFactor?: number;
  /** 这一场关掉的点位（不开门）。读点：`systems/shop.ts` 的 `rollShopStocks` 与界面 */
  closedShopIds?: string[];
  /** 全局涨价加成（0.35 = 本来就贵三成五）。读点：`systems/shop.ts` 的 `rollShopStocks` */
  priceSurcharge?: number;
  /**
   * 事件池权重：`{ 标签: 倍数 }`。读点：`systems/shop.ts` 的 `rollDayEvent`。
   *
   * 它让"这一场会碰上什么事"跟着灾难走（寒潮多"冷"、骚乱多"人"）。
   * 没写标签的事件按 1 倍算 —— 所以只写想强调的那几个标签就行。
   */
  eventPoolWeights?: Record<string, number>;
  /** 有人来敲门的概率乘数（1.3 = 邻居来得更勤）。读点：`systems/help.ts` 的 `rollHelpRequest` */
  npcVisitFactor?: number;

  /**
   * **逐日物价曲线**（§6.2「物价波动」）：`{ 日历天 → 价格倍率 }`。
   *
   * 不写 = 由**这一场的严重度曲线**推出来（见 `data/dayEvents.ts` 的
   * `dayPriceFactor`）：灾难最凶的时候最贵，衰减型的灾难会一路降价。
   * 那对一百多场是够用的默认值。
   *
   * ★ **寒潮写了一份显式的**，而且那一份是**原样搬过来的历史数据**：
   * 它在本项目里是唯一被玩家看过、调过的物价曲线（M2 的"早买还是晚买"就是它撑起来的）。
   * 搬进新算法时我试过用严重度拟合它，最大偏差 0.29 —— 因为
   * **寒潮的严重度曲线本身是抖的**（0.55→0.80→1.0→0.96→1.0），
   * 而那条手写物价表是**肉眼调平的**。
   *
   * ★ 这件事的教训值得留给后来者：**"把它算出来"不一定比"把它写下来"好。**
   * 一条已经被调过、被玩过的曲线，是**数据**，不是**算法的输出**。
   * 硬要用公式复现它，只会得到一条"看起来原理更漂亮、但数值真的变了"的新曲线 ——
   * 而那正是最难被发现的那种改动。
   */
  priceCurve?: Readonly<Record<number, number>>;

  // ———————— §10B.3.1 的 L3 影响维度（第 13~16 维） ————————
  /*
   * ## 为什么 L3 与 L2 要分开写在这一段里
   *
   * L2 那 8 维全是"读一个乘数"——接上去就完事，玩家感受是**生活方式变了**。
   * L3 这 4 维不一样：它们动的是**玩法本身**（某些东西在这里没用、
   * 某些地方去不了、评分标准都不一样），所以每一项都要在该系统的**取值口径**上
   * 想清楚再落，而不是乘一下。§10B.3.1 把这一层的代价标成"中"，
   * 那一栏指的就是这件事。
   */

  /**
   * **品类效率**（维度 13）：同样的东西在这一场更管用 / 更不管用。
   *
   * 例：洪水里 `{ warmth: 0.6 }` —— 棉被吸了潮就不顶用；
   * 大停电里 `{ medicine: 0.8 }` —— 没有电，药能做的事变少了。
   *
   * 它和 `priorityCategories` 是**两件不同的事**，而且混用会坏事：
   *  · `priorityCategories` 回答"**什么最值钱**"（界面标注、顺手位建议）；
   *  · `categoryEfficiency` 回答"**同样的投入能换回多少**"（消耗与恢复的实际效果）。
   * 一件东西可以既是最刚需、又打了折 —— 那正是"这一场不好过"的表达。
   *
   * 读点：`data/survival.ts` 的 `dailyDrainOf` / 自动补给。默认 1。
   */
  categoryEfficiency?: Partial<Record<CategoryId, number>>;
  /**
   * **空间限制**（维度 14）：`0.8` = 可用的货架格子只剩八成（低处进水 / 结冰 / 塌了）。
   *
   * 读点：`systems/setup.ts` 生成货架时，与 `spoilRate` 一样是**乘在盘面上**的，
   * 不是乘在数值上 —— 它直接让"整理这件事"变难，这正是 §10B.0 的主轴
   * （"更大的空间才是奖励"的反面：这一场你**没有**那么大的空间）。
   * 默认 1。
   */
  capacityFactor?: number;
  /**
   * **这一场用不了的家具**（按 `Shelf.id`）。
   *
   * 与 `capacityFactor` 是两个粒度：那个是"整屋小一圈"，
   * 这个是"**这一块**没了"（一楼那块泡在水里、阳台的柜子结了冰）。
   * 后者更能让玩家做出"把东西搬到哪去"的决定。
   */
  unusableShelfIds?: readonly string[];
  /**
   * **健康风险**（维度 15）：硬撑的代价，每天按这个数扣健康（0~3）。
   *
   * 它和"缺货扣健康"的区别是**它不看玩家做错了什么** ——
   * 屋子在漏、空气有毒、水里带菌，只要住在这儿就在掉血。
   * 所以它必须小（1 左右）：它要制造"这一场拖不起"的压力，
   * 不是替玩家把这一局结束掉。读点：`systems/survival.ts` 的日结算。默认 0。
   */
  healthRiskPerDay?: number;
  /**
   * **分数口径**（维度 16）：这一局的评分看什么。
   *
   * 例：`{ emergencyRate: 2 }` —— 这一场里"急诊可达率"比平常更重要。
   * 读点：`model/score.ts`。键就是那里各分项的 key，权重默认 1。
   */
  scoreWeights?: Record<string, number>;

  /**
   * 内容分层，见 `ContentTier`。
   *
   * 灾难的 tier 就是 §10B.3.2 的**解锁阶梯**：
   *   `1` = 开局就有（寒潮）→ `2` = 撑过一次之后 → `3` = 图鉴点亮 8 场之后
   *   → `4` = 撑过 4 个家族 / 特定成就之后。
   * 现在还没有任何代码按它过滤（见 `ContentTier` 的边界说明），
   * 但**解锁阶梯的口径必须先落在数据上**，否则等 110 场内容进来时
   * 就没人说得清"哪几场是新玩家一开局就能撞上的"。
   */
  tier: ContentTier;
  /**
   * §10B.3.2 的**家族**（温度 / 水 / 结构 / 生物 / 社会 / 空气 / 组合）。
   *
   * 它回答"这一场的机制内核是什么"，也是"一百多场怎么不写成一百份手写"的
   * 第一层组织方式：家族决定改哪几个维度，强度档决定改多深，变体决定叙事。
   * 与 `tier` 一起构成解锁阶梯的两个轴（家族 × 层级）。
   */
  family: string;
  /**
   * `'L1' | 'L2' | 'L3' | 'L4'` —— 这一场用到了哪一层的机制（见 §10B.3.1 的实施分层）。
   *
   * L1 只有前 4 维（消耗 / 腐坏 / 刚需 / 温度）——**只改数字**，玩家感受是"更难了"。
   * L2 起开始读"乘数"（屋子坏得更快、睡不安稳、门开得少），感受是**生活方式变了**；
   * L3 开始动**玩法**（某些东西在这里没用、某些地方去不了）；
   * L4 每场一个专属机制。
   *
   * ★ **L1 是被允许的，而且必须允许**（这一条是被校验器逼出来的）：
   * 我原来只写了 L2/L3/L4，于是寒潮 —— 一场只用 4 维、`notes` 里自己写着
   * "下限样板（§10B.3.1 的 L1）"的灾难 —— 把 `level` 标成了 `L2`。
   * 两个字段互相矛盾，而**没有任何东西会发现**，直到 5b 的维度签名校验上线。
   * 一个不允许被如实标注的层级，只会逼出一个假标签。
   *
   * 它不只是标签：`check-registry.mjs` 按它校验"这一场声称的层级，
   * 维度签名里真的够数"—— 声称 L3 却只动了 4 个维度，是"换皮"最典型的样子。
   */
  level: 'L1' | 'L2' | 'L3' | 'L4';
  /** §10B.3 要求的一句话：**这一场的压力轴是什么**（不是"更冷"，而是"哪条线在吃紧"） */
  axis: string;
  /**
   * ★★ 这一场那条**反直觉的侧面**（§10B.3.1 硬要求，`check-content.mjs` 强制必填）。
   *
   * 为什么把它做成必填：一个能从"这场灾难很糟"直接推导出来的效果只是数字；
   * 一个没人会立刻想到、但想通后觉得"确实如此"的效果才是设计。
   * 逼生成者每一场都想一次，是不让"一百多场"退化成"十二种 × 八种数值"的第一道闸。
   */
  counterIntuitive: string;
  /** 这一场逼玩家做的决定（2~4 条，互不重复）。与物品的 `decision` 同一个用途：供人归类查重 */
  decisions?: readonly string[];
  /** 写明本场用到了哪些维度编号（供"维度签名"查同质化）。它由生成者写，校验器核对 */
  notes?: string;
}

