def main() -> None:
    wb = Workbook()

    # —————————————————— 走查表 ——————————————————
    ws = wb.active
    ws.title = "走查表"

    ws["A1"] = "M3 走查表（第 1~4 步）"
    ws["A1"].font = Font(bold=True, size=15, color=INK)
    ws["A2"] = (
        "在「结果」列选一个，「备注」列写你看到的实际情况。没过的把 id 发我即可。"
        "（纯文本版在同目录的 M3-走查表.md，两份条目 id 一致；改一份时记得同步另一份）"
    )
    ws["A2"].font = Font(size=10, color="FF6B6B66")
    ws["A3"] = (
        '="已走 "&COUNTA(F6:F1000)&" 条 ／ 通过 "&COUNTIF(F6:F1000,"通过")'
        '&" ／ 不通过 "&COUNTIF(F6:F1000,"不通过")&" ／ 跳过 "&COUNTIF(F6:F1000,"跳过")'
    )
    ws["A3"].font = Font(bold=True, color=VERMILION)

    header = ["区块", "id", "怎么到达", "看什么", "期望看到什么", "结果", "备注（我看到的是…）"]
    ws.append([])
    ws.append(header)
    head_row = ws.max_row
    for col in range(1, len(header) + 1):
        c = ws.cell(row=head_row, column=col)
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor=PAPER)
        c.border = box
        c.alignment = Alignment(vertical="center", wrap_text=True)

    for r in ROWS:
        ws.append([*r, None, None])

    first_data, last_data = head_row + 1, ws.max_row

    # 结果列：下拉
    dv = DataValidation(type="list", formula1='"通过,不通过,跳过"', allow_blank=True)
    dv.prompt = "选一个"
    dv.promptTitle = "结果"
    ws.add_data_validation(dv)
    dv.add(f"F{first_data}:F{last_data}")

    # 样式
    for row in ws.iter_rows(min_row=first_data, max_row=last_data, min_col=1, max_col=7):
        for c in row:
            c.border = box
            c.alignment = Alignment(vertical="top", wrap_text=True)
        # ★ 条目重的两条（E4/E5/E11/F3/F4）标一点暖黄，提醒"这两条最要紧"
        if row[1].value in ("E4", "E5", "F3", "F4"):
            row[1].fill = PatternFill("solid", fgColor="FFFFF7DC")
        row[1].font = Font(bold=True)

    widths = {"A": 14, "B": 6, "C": 34, "D": 18, "E": 46, "F": 9, "G": 34}
    for col, w in widths.items():
        ws.column_dimensions[col].width = w
    ws.freeze_panes = f"A{first_data}"
    ws.auto_filter.ref = f"A{head_row}:G{last_data}"

    # —————————————————— 说明 ——————————————————
    ws2 = wb.create_sheet("说明")
    ws2["A1"] = "准备步骤与已知项"
    ws2["A1"].font = Font(bold=True, size=14, color=INK)
    ws2.append([])
    for label, text in NOTES:
        ws2.append([label, text])
    for row in ws2.iter_rows(min_row=1, max_row=ws2.max_row, min_col=1, max_col=2):
        for c in row:
            c.alignment = Alignment(vertical="top", wrap_text=True)
    for r in range(3, ws2.max_row + 1):
        if ws2.cell(row=r, column=1).value:
            ws2.cell(row=r, column=1).font = Font(bold=True)
    ws2.column_dimensions["A"].width = 24
    ws2.column_dimensions["B"].width = 78

    out = "docs/M3-走查表.xlsx"
    wb.save(out)
    print(f"写好 {out}")
    print(f"  走查表：{last_data - first_data + 1} 条（{first_data}~{last_data} 行）")
    print(f"  说明：{len(NOTES)} 行")


if __name__ == "__main__":
    main()
